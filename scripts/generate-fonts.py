#!/usr/bin/env python3
"""Generate Kanso Matcha's bundled font @font-face blocks from Fontsource.

Reads the ready-made woff2 files shipped by the @fontsource / @fontsource-variable
packages, base64-encodes them, and emits a SCSS module with @font-face rules
using data: URLs. No subsetting, conversion or renaming is performed.

Run from the project root:
    python3 scripts/generate-fonts.py

Output: styles/_fonts.scss  (compiled first via @use 'fonts' in index.scss)
"""

import base64
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRATCH = Path("/data/data/com.termux/files/usr/tmp/opencode/fonts-scratch")
NODE_MODULES = SCRATCH / "node_modules"
OUTPUT = ROOT / "styles" / "_fonts.scss"

# (package, css_file, family_name, allowed_subsets)
JOBS = [
    ("@fontsource/ibm-plex-sans", "400.css", "IBM Plex Sans", {"latin", "latin-ext"}),
    ("@fontsource/ibm-plex-sans", "500.css", "IBM Plex Sans", {"latin", "latin-ext"}),
    ("@fontsource/ibm-plex-mono", "400.css", "IBM Plex Mono", {"latin", "latin-ext"}),
    ("@fontsource/ibm-plex-mono", "600.css", "IBM Plex Mono", {"latin", "latin-ext"}),
    ("@fontsource/ibm-plex-sans-arabic", "arabic-400.css", "IBM Plex Sans Arabic", {"arabic"}),
    ("@fontsource/ibm-plex-sans-arabic", "arabic-500.css", "IBM Plex Sans Arabic", {"arabic"}),
    ("@fontsource-variable/literata", "wght.css", "Literata", {"latin", "latin-ext"}),
    ("@fontsource-variable/literata", "wght-italic.css", "Literata", {"latin", "latin-ext"}),
    ("@fontsource-variable/noto-naskh-arabic", "wght.css", "Noto Naskh Arabic", {"arabic"}),
]


def _parse_blocks(css: str):
    """Yield (subset_name, style, weight, woff2_relpath, format, unicode_range)."""
    for comment, block in re.findall(r"/\*\s*([^\*]+?)\s*\*/\s*@font-face\s*\{([^}]*)\}", css):
        subset_name = comment.strip().split("-")[-3] if False else None
        # subset name is the token before the weight/style in the comment,
        # e.g. "ibm-plex-sans-latin-400-normal" -> "latin"
        parts = comment.strip().split("-")
        # find subset token: known subset names
        subset_token = None
        for tok in parts:
            if tok in {"latin", "latin-ext", "arabic", "cyrillic", "cyrillic-ext",
                       "greek", "greek-ext", "vietnamese", "math", "symbols"}:
                subset_token = tok
                break
        if subset_token is None:
            continue
        style_m = re.search(r"font-style:\s*(\w+)", block)
        weight_m = re.search(r"font-weight:\s*([\d\s]+)", block)
        src_m = re.search(r"src:\s*url\(([^)]+\.woff2)\)\s*format\('([^']+)'\)", block)
        range_m = re.search(r"unicode-range:\s*([^;]+);", block)
        if not (style_m and weight_m and src_m):
            continue
        yield {
            "subset": subset_token,
            "style": style_m.group(1),
            "weight": weight_m.group(1).strip(),
            "src": src_m.group(1).strip().lstrip("./"),
            "fmt": src_m.group(2),
            "unicode_range": range_m.group(1).strip() if range_m else None,
        }


def _b64(path: Path) -> str:
    return base64.b64encode(path.read_bytes()).decode("ascii")


def main():
    out_lines = [
        "/* Kanso Matcha: fonts */",
        "/*",
        " * Bundled fonts (base64-encoded woff2) for the Morning Matcha /",
        " * Evening Zen type system. Generated by scripts/generate-fonts.py",
        " * from @fontsource / @fontsource-variable packages. Do not edit by hand.",
        " *",
        " * Credits:",
        " *   IBM Plex Sans, IBM Plex Mono, IBM Plex Sans Arabic",
        " *     (c) 2017 IBM Corp. — SIL Open Font License 1.1",
        " *   Literata",
        " *     (c) 2016-2024 TypeTogether — SIL Open Font License 1.1",
        " *   Noto Naskh Arabic",
        " *     (c) 2012-2024 Google Inc. — SIL Open Font License 1.1",
        " * Full license text: FONT-LICENSES.txt",
        " */",
        "",
    ]
    count = 0
    for package, css_file, family, allowed in JOBS:
        pkg_dir = NODE_MODULES / package
        css_path = pkg_dir / css_file
        css = css_path.read_text(encoding="utf-8")
        for face in _parse_blocks(css):
            if face["subset"] not in allowed:
                continue
            woff2_path = pkg_dir / face["src"]
            if not woff2_path.is_file():
                raise FileNotFoundError(woff2_path)
            b64 = _b64(woff2_path)
            out_lines.append("@font-face {")
            out_lines.append(f'  font-family: "{family}";')
            out_lines.append(f'  font-style: {face["style"]};')
            out_lines.append("  font-display: swap;")
            out_lines.append(f"  font-weight: {face['weight']};")
            out_lines.append(
                f'  src: url("data:font/woff2;base64,{b64}") format("{face["fmt"]}");'
            )
            if face["unicode_range"]:
                out_lines.append(f"  unicode-range: {face['unicode_range']};")
            out_lines.append("}")
            out_lines.append("")
            count += 1
    OUTPUT.write_text("\n".join(out_lines), encoding="utf-8")
    print(f"Wrote {OUTPUT} with {count} @font-face rules.")


if __name__ == "__main__":
    main()
